#!/usr/bin/env bash
# Write a .env file from the current process environment (known Blink keys only).
# Never prints secret values. Refuses to overwrite unless FORCE=1.
# Escapes $ → $$ so Docker Compose interpolation does not truncate secrets.
set -euo pipefail

OUT="${1:-.env}"
FORCE="${FORCE:-0}"

if [[ -f "$OUT" && "$FORCE" != "1" ]]; then
  echo "Refusing to overwrite $OUT (set FORCE=1)" >&2
  exit 1
fi

require() {
  local name="$1"
  if [[ -z "${!name:-}" ]]; then
    echo "Missing required env: $name" >&2
    exit 1
  fi
}

# Escape for Compose .env interpolation ($VAR / ${VAR}).
compose_escape() {
  printf '%s' "${1:-}" | sed 's/\$/$$/g'
}

require BLINK_PASSWORD
require BLINK_API_KEY
require BLINK_SESSION_SECRET
require POSTGRES_PASSWORD

POSTGRES_USER="${POSTGRES_USER:-blink}"
POSTGRES_DB="${POSTGRES_DB:-blink}"
BLINK_BASE_URL="${BLINK_BASE_URL:-https://layurl.com}"
DATABASE_URL="${DATABASE_URL:-postgres://${POSTGRES_USER}:${POSTGRES_PASSWORD}@postgres:5432/${POSTGRES_DB}}"

# shellcheck disable=SC2016
{
  echo "# Generated by deploy/scripts/render-env.sh — do not commit"
  echo "BLINK_BASE_URL=$(compose_escape "$BLINK_BASE_URL")"
  echo "BLINK_SITE_TITLE=$(compose_escape "${BLINK_SITE_TITLE:-Blink}")"
  echo "BLINK_PASSWORD=$(compose_escape "$BLINK_PASSWORD")"
  echo "BLINK_API_KEY=$(compose_escape "$BLINK_API_KEY")"
  echo "BLINK_SESSION_SECRET=$(compose_escape "$BLINK_SESSION_SECRET")"
  echo "BLINK_PUBLIC_MODE=$(compose_escape "${BLINK_PUBLIC_MODE:-false}")"
  echo "BLINK_TURNSTILE_SITE_KEY=$(compose_escape "${BLINK_TURNSTILE_SITE_KEY:-}")"
  echo "BLINK_TURNSTILE_SECRET_KEY=$(compose_escape "${BLINK_TURNSTILE_SECRET_KEY:-}")"
  echo "BLINK_TURNSTILE_FORCE=$(compose_escape "${BLINK_TURNSTILE_FORCE:-false}")"
  echo "BLINK_URL_CHECK_PROVIDER=$(compose_escape "${BLINK_URL_CHECK_PROVIDER:-none}")"
  echo "BLINK_URL_CHECK_BLOCKLIST_PATH=$(compose_escape "${BLINK_URL_CHECK_BLOCKLIST_PATH:-}")"
  echo "BLINK_URL_CHECK_HTTP_URL=$(compose_escape "${BLINK_URL_CHECK_HTTP_URL:-}")"
  echo "BLINK_URL_CHECK_HTTP_TIMEOUT_MS=$(compose_escape "${BLINK_URL_CHECK_HTTP_TIMEOUT_MS:-5000}")"
  echo "POSTGRES_USER=$(compose_escape "$POSTGRES_USER")"
  echo "POSTGRES_PASSWORD=$(compose_escape "$POSTGRES_PASSWORD")"
  echo "POSTGRES_DB=$(compose_escape "$POSTGRES_DB")"
  echo "DATABASE_URL=$(compose_escape "$DATABASE_URL")"
  echo "REDIS_URL=$(compose_escape "${REDIS_URL:-redis://redis:6379}")"
  echo "GHCR_OWNER=$(compose_escape "${GHCR_OWNER:-kyroskoh}")"
  echo "BLINK_IMAGE_TAG=$(compose_escape "${BLINK_IMAGE_TAG:-latest}")"
  echo "CLOUDFLARE_API_TOKEN=$(compose_escape "${CLOUDFLARE_API_TOKEN:-}")"
  echo "CLOUDFLARE_ZONE_ID=$(compose_escape "${CLOUDFLARE_ZONE_ID:-}")"
  echo "CLOUDFLARE_ORIGIN_IPV4=$(compose_escape "${CLOUDFLARE_ORIGIN_IPV4:-}")"
  echo "CLOUDFLARE_ORIGIN_IPV6=$(compose_escape "${CLOUDFLARE_ORIGIN_IPV6:-}")"
  echo "CLOUDFLARE_MANAGE_WWW=$(compose_escape "${CLOUDFLARE_MANAGE_WWW:-true}")"
  echo "BLINK_LETSENCRYPT_EMAIL=$(compose_escape "${BLINK_LETSENCRYPT_EMAIL:-}")"
} >"$OUT"

echo "Wrote $OUT (secrets redacted from this log)"
